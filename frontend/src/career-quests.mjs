export function careerQuest(ruler, rulerSignIndex, skillIndex) {
  const styleIndex = rulerSignIndex % STYLES.length;
  const [style, styleHint] = STYLES[styleIndex];
  const baseJob = JOBS[ruler.house - 1];
  const branch = JOB_BRANCHES[ruler.house]?.[ruler.name];
  const entry = branch || (ruler.house === 1 && WARRIOR_STYLES[styleIndex]) || baseJob;
  const [job, technique, signature, title, mission, clear, workTitle, workAction, measure] = entry;
  return { job, technique, signature, title, mission, clear, style, styleHint, practice: PRACTICE[skillIndex], workTitle, workAction, measure };
}
