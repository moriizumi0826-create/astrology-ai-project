def main():
    # 文字コード検出（BOM 有無で対応）
    raw = DB_PATH.read_bytes()
    encoding = 'utf-8-sig' if raw[:3] == b'\xef\xbb\xbf' else 'utf-8'

    with DB_PATH.open('r', encoding=encoding, newline='') as f:
        reader = csv.reader(f)
        rows = list(reader)

    updated = 0
    for row in rows:
        if len(row) < 14:
            continue
        key = (row[0], row[1], row[2], row[4], row[5], row[6], row[7])
        if key in CONTENT and row[8] == '':   # Text_Description が空の行だけ上書き
            cat, txt, label, score, priority, task = CONTENT[key]
            row[3]  = cat
            row[8]  = txt
            row[9]  = label
            row[10] = ''        # Countdown_ID は空欄維持
            row[11] = score
            row[12] = priority
            row[13] = task
            updated += 1

    # BOM 付きで書き戻し（元ファイルに合わせる）
    with DB_PATH.open('w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f)
        writer.writerows(rows)

    print(f"完了: {updated} 行を更新しました")


if __name__ == '__main__':
    main()
